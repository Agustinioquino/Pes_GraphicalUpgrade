const char* TRS(const char* es) {
    if (!es || g_cfg.lang == 0) return es;
    using Map = std::unordered_map<std::string, const char*>;
    static const Map mEn = [] { Map r; for (auto& p : kEn) r.emplace(p[0], p[1]); return r; }();
    static const Map mPt = [] { Map r; for (auto& p : kPt) r.emplace(p[0], p[1]); return r; }();
    const Map& m = g_cfg.lang == 2 ? mPt : mEn;
    auto it = m.find(es);
    return it == m.end() ? es : it->second;
}

