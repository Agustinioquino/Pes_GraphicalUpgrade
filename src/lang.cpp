const char* TRS(const char* es) {
    if (!es || g_cfg.lang != 1) return es;
    static const std::unordered_map<std::string, const char*> m = [] {
        std::unordered_map<std::string, const char*> r;
        for (auto& p : kEn) r.emplace(p[0], p[1]);
        return r;
    }();
    auto it = m.find(es);
    return it == m.end() ? es : it->second;
}

